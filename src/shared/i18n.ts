const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { pl, en };

export function isLanguage(value: unknown): value is Language {
  return value === "pl" || value === "en";
}

/** Translate `key`, substituting `{name}`-style placeholders from `params`. */
export function translate(
  language: Language,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const template = DICTIONARIES[language]?.[key] ?? DICTIONARIES.pl[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match
  );
}

/** Bind a language once and get a `t()` for it. */
export function createTranslator(language: Language) {
  return (key: TranslationKey, params?: Record<string, string | number>) =>
    translate(language, key, params);
}

export type Translator = ReturnType<typeof createTranslator>;
